#!/usr/bin/env bash
# Regenerate the in-repo package manifests for a published release:
#   Formula/claude-code-sync.rb     Homebrew  (this repo doubles as the tap)
#   bucket/claude-code-sync.json    Scoop     (this repo doubles as the bucket)
#
# Usage: scripts/update-packaging.sh v0.3.3
#
# Checksums come from the .sha256 files the release workflow uploads next to
# each asset. A platform whose asset is missing from the release is left out
# of the manifests rather than failing, so older releases still render.
# Run by release.yml after the binaries are uploaded; safe to run by hand.

set -euo pipefail

REPO="perfectra1n/claude-code-sync"
tag="${1:?usage: $0 <tag, e.g. v0.3.3>}"
[[ "$tag" == v* ]] || tag="v$tag"
version="${tag#v}"
base="https://github.com/$REPO/releases/download/$tag"
root="$(cd "$(dirname "$0")/.." && pwd)"

# Print the sha256 for a release asset, or nothing if the release lacks it.
sha_of() {
    local body
    body=$(curl -fsSL --retry 3 "$base/$1.sha256" 2>/dev/null) || return 0
    printf '%s' "${body%% *}"
}

# --- Homebrew --------------------------------------------------------------

# Linux uses the static musl builds: brew's own glibc can be older than the
# runner the gnu builds were linked on.
brew_block() { # <indent> <asset>
    local sha
    sha=$(sha_of "$2")
    [[ -n "$sha" ]] || return 0
    printf '%surl "%s/%s"\n%ssha256 "%s"\n' "$1" "$base" "$2" "$1" "$sha"
}

brew_arch() { # <on_arm|on_intel> <asset>
    local body
    body=$(brew_block "      " "$2")
    [[ -n "$body" ]] || return 0
    printf '    %s do\n%s\n    end\n' "$1" "$body"
}

brew_os() { # <on_macos|on_linux> <arm asset> <intel asset>
    local arm intel body
    # $(...) strips trailing newlines, so rejoin the two blocks explicitly.
    arm=$(brew_arch on_arm "$2")
    intel=$(brew_arch on_intel "$3")
    body="$arm${arm:+${intel:+$'\n'}}$intel"
    [[ -n "$body" ]] || return 0
    printf '  %s do\n%s\n  end\n\n' "$1" "$body"
}

mkdir -p "$root/Formula"
{
    cat <<EOF
# Generated by scripts/update-packaging.sh on each release; do not edit by hand.
class ClaudeCodeSync < Formula
  desc "Sync Claude Code conversation history with git repositories"
  homepage "https://github.com/$REPO"
  version "$version"
  license "MIT"

EOF
    brew_os on_macos claude-code-sync-macos-aarch64.tar.gz claude-code-sync-macos-x86_64.tar.gz
    brew_os on_linux claude-code-sync-linux-aarch64-musl.tar.gz claude-code-sync-linux-x86_64-musl.tar.gz
    cat <<'EOF'
  def install
    bin.install "claude-code-sync"
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/claude-code-sync --version")
  end
end
EOF
} >"$root/Formula/claude-code-sync.rb"

# --- Scoop -----------------------------------------------------------------

scoop_arch() { # <scoop arch key> <asset>
    local sha
    sha=$(sha_of "$2")
    [[ -n "$sha" ]] || return 0
    jq -n --arg key "$1" --arg url "$base/$2" --arg hash "$sha" '{($key): {url: $url, hash: $hash}}'
}

autoupdate_arch() { # <scoop arch key> <asset>
    jq -n --arg key "$1" \
        --arg url "https://github.com/$REPO/releases/download/v\$version/$2" \
        '{($key): {url: $url, hash: {url: "$url.sha256"}}}'
}

mkdir -p "$root/bucket"
jq -n \
    --arg version "$version" \
    --arg homepage "https://github.com/$REPO" \
    --argjson arch "$(
        { scoop_arch 64bit claude-code-sync-windows-x86_64.exe.zip
          scoop_arch arm64 claude-code-sync-windows-aarch64.exe.zip; } | jq -s 'add // {}'
    )" \
    --argjson auto "$(
        { autoupdate_arch 64bit claude-code-sync-windows-x86_64.exe.zip
          autoupdate_arch arm64 claude-code-sync-windows-aarch64.exe.zip; } | jq -s add
    )" \
    '{
        version: $version,
        description: "Sync Claude Code conversation history with git repositories",
        homepage: $homepage,
        license: "MIT",
        architecture: $arch,
        bin: "claude-code-sync.exe",
        checkver: "github",
        autoupdate: {architecture: $auto}
    }' >"$root/bucket/claude-code-sync.json"

[[ "$(jq '.architecture | length' "$root/bucket/claude-code-sync.json")" -gt 0 ]] ||
    { echo "error: no Windows assets found for $tag" >&2; exit 1; }
grep -q 'sha256' "$root/Formula/claude-code-sync.rb" ||
    { echo "error: no macOS/Linux assets found for $tag" >&2; exit 1; }

echo "Updated Formula/claude-code-sync.rb and bucket/claude-code-sync.json for $tag"
